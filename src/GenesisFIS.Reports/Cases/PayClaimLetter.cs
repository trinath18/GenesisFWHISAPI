using GenesisFIS.Core.Cases;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace GenesisFIS.Reports.Cases;

/// <summary>Replaces the Word Pay and Claim letter: states why cashless cover cannot be given and that the member should pay and claim.</summary>
public static class PayClaimLetter
{
    static PayClaimLetter() => QuestPDF.Settings.License = LicenseType.Community;
    private static string D(DateOnly? d) => d?.ToString("dd/MM/yyyy") ?? "-";

    public static byte[] ToPdf(CasePayClaimView v, string issuedBy)
    {
        var rec = v.Record!;
        var reasons = new List<string>();
        if (rec.InfoInv) reasons.Add("Further information/investigation is required on your condition");
        if (rec.NonPan) reasons.Add("Non-Panel Hospital");
        if (rec.NonCash) reasons.Add("No cashless 90 days");
        if (rec.CovgSub) reasons.Add("Coverage subject to Radiology/Scan result which is pending");
        if (rec.ConfInfo) reasons.Add("Conflicting information provided");
        if (rec.Lab) reasons.Add("Awaiting lab test result which is pending");
        if (rec.OthersChecked && !string.IsNullOrWhiteSpace(rec.Others)) reasons.Add(rec.Others!);
        return Document.Create(doc => doc.Page(page =>
        {
            page.Size(PageSizes.A4); page.Margin(40); page.DefaultTextStyle(x => x.FontSize(10));
            page.Header().Column(c => { c.Item().Text("PAY & CLAIM").FontSize(15).Bold(); c.Item().Text($"Date: {D(rec.Date)}    Case No: {v.CaseNumber}").FontColor(Colors.Grey.Darken2); c.Item().PaddingBottom(8).LineHorizontal(1); });
            page.Content().Column(c =>
            {
                c.Spacing(8);
                foreach (var (l, val) in new[] { ("Principal name", v.PrincipalName), ("Membership No", v.MemberNumber), ("Policy No", v.PolicyNo ?? "-"), ("Patient name", v.PatientName), ("Date of admission", D(v.Admitted)), ("Date of discharge", D(v.Discharged)) })
                    c.Item().Row(r => { r.ConstantItem(140).Text(l).FontColor(Colors.Grey.Darken2); r.RelativeItem().Text(val); });
                c.Item().Text("We are unable to extend a cashless facility for the above admission for the following reason(s). Please settle the hospital bill and submit a claim for reimbursement:");
                foreach (var r in reasons) c.Item().Text("- " + r);
                c.Item().Text("Issued by " + issuedBy).FontColor(Colors.Grey.Darken2);
            });
            page.Footer().Text("Generated by Genesis FIS").FontSize(8).FontColor(Colors.Grey.Medium);
        })).GeneratePdf();
    }
}
