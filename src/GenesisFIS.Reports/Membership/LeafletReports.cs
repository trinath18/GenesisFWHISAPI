using ClosedXML.Excel;
using GenesisFIS.Core.Membership;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace GenesisFIS.Reports.Membership;

/// <summary>
/// Replaces the Crystal reports of Membership &gt; Leaflet &amp; Card: Leaflet.rpt, Leaflet_GrpCo.rpt and Leaflet_GrpCo_EmpNo.rpt (VIEW_LEAFLET), and the
/// card export workbook (testing.xls filled from VIEW_CardPrinting). The .rpt files only give the fields and formulas, not the printed wording,
/// and testing.xls is not in the repository, so the layouts here are drafted around the same fields; swap in the approved wording if it differs.
/// </summary>
public static class LeafletReports
{
    static LeafletReports() => QuestPDF.Settings.License = LicenseType.Community;

    private static string V(string? s) => string.IsNullOrWhiteSpace(s) ? "-" : s;

    /// <summary>The @MBMAgentCo formula: the policy number followed by "(agent code)" when there is one.</summary>
    public static string PolicyWithAgent(string? policyNo, string? agentCode) =>
        (policyNo?.Trim() ?? "") + (string.IsNullOrWhiteSpace(agentCode) ? "" : $" ({agentCode.Trim()})");

    /// <summary>One A4 leaflet per member: address block, membership details, the card and any supplementary cards.</summary>
    public static byte[] Leaflets(IReadOnlyList<LeafletDocument> leaflets, string version, DateOnly printed) => Document.Create(doc =>
    {
        foreach (var l in leaflets)
            doc.Page(page =>
            {
                page.Size(PageSizes.A4); page.Margin(40); page.DefaultTextStyle(x => x.FontSize(10));
                page.Header().Column(c =>
                {
                    c.Item().Text(V(l.PayorName)).FontSize(13).Bold();
                    c.Item().Text($"Date: {printed:dd/MM/yyyy}").FontColor(Colors.Grey.Darken2);
                    c.Item().PaddingBottom(8).LineHorizontal(1);
                });
                page.Content().Column(c =>
                {
                    c.Spacing(8);
                    c.Item().Text(string.Join("\n", new[] { l.Name, l.Address1, l.Address2, l.Address3, l.PostCode }.Where(x => !string.IsNullOrWhiteSpace(x))));
                    var fields = new List<(string, string?)> { ("Membership No", l.MemberNumber), ("Policy No", PolicyWithAgent(l.PolicyNo, l.AgentCode)) };
                    if (version is LeafletLists.ByGroupCompany or LeafletLists.ByDeptEmployee) fields.Add(("Group Company", l.GroupCompany));
                    if (version == LeafletLists.ByDeptEmployee) { fields.Add(("Department", l.Department)); fields.Add(("Employee No", l.EmployeeNo)); }
                    foreach (var (label, value) in fields)
                        c.Item().Row(r => { r.ConstantItem(120).Text(label).FontColor(Colors.Grey.Darken2); r.RelativeItem().Text(V(value)); });
                    c.Item().PaddingTop(6).Text("Dear Member,").Bold();
                    c.Item().Text($"Enclosed is your medical card issued on behalf of {V(l.PayorName)}. Please present the card together with your identity document "
                        + "at any panel hospital when seeking admission. Please check the details below and inform us if any of them is incorrect.");
                    c.Item().PaddingTop(10).Row(r =>
                    {
                        r.ConstantItem(250).Element(e => Card(e, l, l.Name, l.MemberNumber, "Membership Card"));
                    });
                    if (l.HasSupplementaryCards)
                        foreach (var p in l.Covered)
                            c.Item().Row(r => r.ConstantItem(250).Element(e => Card(e, l, p.Name, $"{l.MemberNumber} - {p.CoverId}", "Supplementary Card")));
                });
                page.Footer().Text("Generated by Genesis FIS").FontSize(8).FontColor(Colors.Grey.Medium);
            });
    }).GeneratePdf();

    private static void Card(IContainer e, LeafletDocument l, string? name, string number, string title) =>
        e.Border(1).Padding(8).Column(k =>
        {
            k.Item().Text(V(l.PayorName)).FontSize(8).FontColor(Colors.Grey.Darken2);
            k.Item().Text(title).FontSize(9).Bold();
            k.Item().PaddingTop(6).Text(V(name)).Bold();
            k.Item().Text($"Member No: {number}").FontSize(9);
            k.Item().Text($"Policy No: {V(PolicyWithAgent(l.PolicyNo, l.AgentCode))}").FontSize(9);
        });

    /// <summary>
    /// The card export sheet of the legacy export routine: payor, bordereaux date and file name (payor code + yymmdd) in A1:A3, then one line per card
    /// (running number, name, IC / BC / passport, policy no, member no-cover id, plan, payor expiry). The version adds the group company or department
    /// and employee number columns, as the leaflet versions do.
    /// </summary>
    public static byte[] CardExport(IReadOnlyList<CardExportLine> lines, string? payorName, string? payorCode, DateOnly? bordxDate, string version)
    {
        using var wb = new XLWorkbook();
        var ws = wb.AddWorksheet("Card Export");
        ws.Cell(1, 1).Value = payorName ?? "";
        ws.Cell(2, 1).Value = bordxDate?.ToString("dd/MM/yyyy") ?? "";
        ws.Cell(3, 1).Value = FileName(payorCode, bordxDate);
        var headers = new List<string> { "No", "Name", "IC / BC / Passport", "Policy No", "Member No", "Plan", "Payor Expiry" };
        if (version is LeafletLists.ByGroupCompany or LeafletLists.ByDeptEmployee) headers.Add("Group Company");
        if (version == LeafletLists.ByDeptEmployee) headers.AddRange(["Department", "Employee No"]);
        for (var i = 0; i < headers.Count; i++) ws.Cell(4, i + 1).Value = headers[i];
        ws.Row(4).Style.Font.Bold = true;

        var row = 5;
        foreach (var l in lines)
        {
            var values = new List<XLCellValue> { row - 4, l.Name ?? "", l.IcBcPp ?? "", l.PolicyNo ?? "", $"{l.MemberNumber}-{l.CoverId}", l.PlanCode ?? "" };
            values.Add(l.PayorExpDate is { } exp ? exp.ToDateTime(TimeOnly.MinValue) : Blank.Value);
            if (version is LeafletLists.ByGroupCompany or LeafletLists.ByDeptEmployee) values.Add(l.GroupCompany ?? "");
            if (version == LeafletLists.ByDeptEmployee) { values.Add(l.Department ?? ""); values.Add(l.EmployeeNo ?? ""); }
            for (var i = 0; i < values.Count; i++) ws.Cell(row, i + 1).Value = values[i];
            ws.Cell(row, 7).Style.DateFormat.Format = "dd/mm/yyyy";
            row++;
        }
        ws.Columns().AdjustToContents();
        using var ms = new MemoryStream();
        wb.SaveAs(ms);
        return ms.ToArray();
    }

    /// <summary>tmpFileName of the legacy export: payor code followed by the bordereaux date as yymmdd.</summary>
    public static string FileName(string? payorCode, DateOnly? bordxDate) => (payorCode?.Trim() ?? "") + (bordxDate?.ToString("yyMMdd") ?? "");
}
